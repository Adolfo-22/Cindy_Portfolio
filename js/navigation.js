const nav = document.querySelector('.site-nav');
const menuToggle = document.querySelector('#menu-toggle');
menuToggle?.addEventListener('click', () => { const open = nav.classList.toggle('open'); menuToggle.setAttribute('aria-expanded', String(open)); });
document.querySelectorAll('.nav-link, .footer-links a').forEach(link => link.addEventListener('click', () => { nav.classList.remove('open'); menuToggle?.setAttribute('aria-expanded','false'); }));
const sections = [...document.querySelectorAll('main section[id]')];
const navLinks = [...document.querySelectorAll('.nav-link')];
const sectionObserver = new IntersectionObserver(entries => entries.forEach(entry => { if(entry.isIntersecting){ navLinks.forEach(link => link.classList.toggle('active', link.getAttribute('href') === `#${entry.target.id}`)); } }), {rootMargin:'-35% 0px -55% 0px'});
sections.forEach(section => sectionObserver.observe(section));
document.querySelector('#print-button')?.addEventListener('click', () => window.print());
const backTop = document.querySelector('#back-top');
window.addEventListener('scroll', () => backTop.classList.toggle('visible', window.scrollY > 650), {passive:true});
backTop.addEventListener('click', () => window.scrollTo({top:0, behavior:'smooth'}));
